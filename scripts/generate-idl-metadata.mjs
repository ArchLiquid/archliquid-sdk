import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const programs = { archCurve: "arch_curve", archSwap: "arch_swap", archLocker: "arch_locker" };
const integerSizes = { bool: 1, u8: 1, i8: 1, u16: 2, i16: 2, u32: 4, i32: 4, f32: 4,
  u64: 8, i64: 8, f64: 8, u128: 16, i128: 16, u256: 32, i256: 32, pubkey: 32 };

function fixedSize(type, types) {
  if (typeof type === "string") {
    assert.ok(Object.hasOwn(integerSizes, type), `Unsupported variable-sized account field: ${type}`);
    return integerSizes[type];
  }
  if (type.array) return fixedSize(type.array[0], types) * type.array[1];
  if (type.defined) {
    const definition = types.get(type.defined.name);
    assert.ok(definition, `Missing IDL type ${type.defined.name}`);
    if (definition.kind === "struct") return definition.fields.reduce((sum, field) => sum + fixedSize(field.type, types), 0);
    if (definition.kind === "enum") {
      const sizes = definition.variants.map((variant) => (variant.fields ?? []).reduce((sum, field) => sum + fixedSize(field.type ?? field, types), 0));
      assert.ok(sizes.every((size) => size === sizes[0]), "Account enums must have equal fixed-size variants");
      return 1 + (sizes[0] ?? 0);
    }
  }
  throw new Error(`Unsupported fixed-size IDL type: ${JSON.stringify(type)}`);
}

const metadata = {};
for (const [program, filename] of Object.entries(programs)) {
  const bytes = await readFile(new URL(`../idl/${filename}.json`, import.meta.url));
  assert.ok(!bytes.includes(13), `${filename}: governed IDL bytes must use LF`);
  const idl = JSON.parse(bytes.toString("utf8"));
  const types = new Map(idl.types.map((entry) => [entry.name, entry.type]));
  metadata[program] = {
    programAddress: idl.address,
    idlSha256: createHash("sha256").update(bytes).digest("hex"),
    accounts: Object.fromEntries(idl.accounts.map((account) => [account.name, {
      discriminator: account.discriminator,
      size: account.discriminator.length + fixedSize({ defined: { name: account.name } }, types),
    }])),
    events: Object.fromEntries((idl.events ?? []).map((event) => [event.name, event.discriminator])),
    errors: idl.errors,
  };
}

const generated = `// Generated by scripts/generate-idl-metadata.mjs from exact governed LF IDL bytes.\n// Update IDLs deliberately, then run npm run generate:idl; never edit this file by hand.\n\nfunction freezeMetadata<T>(value: T): T {\n  if (value !== null && typeof value === "object") {\n    for (const child of Object.values(value)) freezeMetadata(child);\n    Object.freeze(value);\n  }\n  return value;\n}\n\nexport const OWNED_IDL_METADATA = freezeMetadata(${JSON.stringify(metadata, null, 2)} as const);\n`;
const destination = new URL("../src/owned-idl-metadata.ts", import.meta.url);
if (process.argv.includes("--check")) {
  assert.equal(await readFile(destination, "utf8"), generated, "Generated IDL metadata drifted; review IDL changes and run npm run generate:idl");
  console.log("Generated IDL metadata is current.");
} else {
  await writeFile(destination, generated);
  console.log("Generated immutable IDL metadata for Curve, Swap and Locker.");
}
